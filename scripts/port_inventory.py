#!/usr/bin/env python3
"""Refresh the port inventory from the checked declaration index and import boundary.

This records the current surface; it does not prescribe rewrites from filename or size
heuristics. Run after ExtractDecls.lean and reorg.py --gen-aggregators.
"""
import collections
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
surface = json.loads((ROOT / "atlas/import_surface.json").read_text())
by_module = collections.defaultdict(list)
for declaration in json.loads((ROOT / "atlas/declarations.json").read_text()):
    by_module[declaration["module"]].append(declaration)

entries = []
for path in sorted((ROOT / "NLAlib").rglob("*.lean")):
    if path.with_suffix("").is_dir() or path.name == "Experimental.lean":
        continue
    module = ".".join(path.relative_to(ROOT).with_suffix("").parts)
    declarations = by_module[module]
    causes = surface["excluded_modules"].get(module, [])
    entries.append({
        "module": module,
        "path": str(path.relative_to(ROOT)),
        "lines": len(path.read_text().splitlines()),
        "surface": "experimental" if causes else "default",
        "experimental_dependencies": causes,
        "public_declarations": len(declarations),
        "sorry_declarations": sorted(d["name"] for d in declarations if d["sorry"]),
        "atlas_ids": sorted({i for d in declarations for i in d["atlas"]}),
    })

inventory = {
    "schema_version": 2,
    "policy": "Preserve the reviewed API and Mathlib interfaces. Move experimental modules "
              "only with explicit status. No automatic merge, drop, or rebuild decisions.",
    "inputs": ["atlas/declarations.json", "atlas/import_surface.json", "NLAlib/**/*.lean"],
    "entries": entries,
}
(ROOT / "docs/port/manifest.json").write_text(
    json.dumps(inventory, ensure_ascii=False, indent=1) + "\n")
counts = collections.Counter((e["module"].split(".")[1], e["surface"]) for e in entries)
rows = ["| Area | Default content modules | Experimental content modules |",
        "|---|---:|---:|"]
for area in sorted({area for area, _ in counts}):
    rows.append(f"| {area} | {counts[area, 'default']} | {counts[area, 'experimental']} |")
text = """# Current port inventory

Generated by `python3 scripts/port_inventory.py` from the source tree, declaration index,
and explicit import boundary. [manifest.json](manifest.json) lists every content module,
its default/experimental import status, public declarations, transitive unfinished-proof
dependencies, and atlas result ids. Directory aggregators are omitted.

This replaces the pre-audit merge/drop/rebuild plan. In particular, finite probability
calculations and useful bundled interfaces are not reasons to rebuild or discard a module.
The sampling and solver APIs now expose native probability laws and integral bridges.
Any further consolidation should follow mathematical topics and import dependencies,
with checked call-site migrations.

""" + "\n".join(rows) + """

The default surface is checked by `scripts/AuditTrusted.lean`; the full development is
indexed through `NLAlib.Experimental`. Module exclusion is conservative: a module importing
an experimental module is excluded even when some individual declarations are independent
of its unfinished proofs. Consult each declaration's `sorry` field for that finer distinction.

This inventory is not a claim that every public contract has been individually reviewed.
See the [compatibility audit](../review/MATHLIB_COMPATIBILITY_AUDIT_2026-10-13.md) and its
implementation follow-up for the changes and remaining mathematical scope. The scripts in
`tools/` are historical inputs to the retired plan; they are not the current generator.
"""
(ROOT / "docs/port/MANIFEST.md").write_text(text)
print(f"port inventory: {len(entries)} content modules")
