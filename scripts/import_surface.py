#!/usr/bin/env python3
"""Generate/check the default, scaffold-free import surface.

The explicit experimental module list determines the boundary; this script never
silently excludes a newly introduced sorry. AuditTrusted.lean checks actual axioms.
Run after regenerating topic aggregators, or use --check in CI.
"""
import argparse
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent


def surfaces():
    paths = {".".join(p.relative_to(ROOT).with_suffix("").parts): p
             for p in (ROOT / "NLAlib").rglob("*.lean")
             if p != ROOT / "NLAlib/Experimental.lean"}
    edges = {m: set(re.findall(r"^(?:public )?import (NLAlib(?:\.\w+)*)\s*$",
                              p.read_text(), re.M)) for m, p in paths.items()}
    for m, deps in edges.items():
        missing = deps - paths.keys()
        if missing:
            raise ValueError(f"{m}: missing or forbidden umbrella imports {sorted(missing)}")
    roots = {line.split("#", 1)[0].strip() for line in
             (ROOT / "scripts/experimental_modules.txt").read_text().splitlines()}
    roots.discard("")
    if roots - paths.keys():
        raise ValueError(f"Unknown experimental modules: {sorted(roots - paths.keys())}")
    causes = {m: ({m} if m in roots else set()) for m in paths}
    while True:
        changed = False
        for m, deps in edges.items():
            inherited = set().union(*(causes[d] for d in deps)) if deps else set()
            if not inherited <= causes[m]:
                causes[m].update(inherited)
                changed = True
        if not changed:
            break
    safe = {m for m in paths if not causes[m]}
    imported = {d for m in safe for d in edges[m]}
    imports = sorted(safe - imported)
    # Check coverage, including malformed cycles which would otherwise disappear.
    reachable = set(imports)
    while True:
        expanded = reachable | {d for m in reachable for d in edges[m]}
        if expanded == reachable:
            break
        reachable = expanded
    if reachable != safe:
        raise ValueError(f"Default surface has unreachable modules: {sorted(safe - reachable)}")
    default = "".join(f"import {m}\n" for m in imports)
    default += ("\n/-! # NLAlib\n\nThe default import excludes experimental modules and their import dependants.\n"
                "Every library declaration reachable here is checked by `scripts/AuditTrusted.lean`.\n"
                "For the complete development, including unfinished proofs, import `NLAlib.Experimental`.\n"
                "Generated by `scripts/import_surface.py`; see `atlas/import_surface.json`. -/\n")
    tops = sorted(p.name for p in (ROOT / "NLAlib").iterdir() if p.is_dir())
    experimental = "".join(f"import NLAlib.{name}\n" for name in tops)
    experimental += ("\n/-! # Complete experimental development\n\nThis import includes unfinished proofs and their dependants. Use `import NLAlib`\n"
                     "for the scaffold-free surface. The declaration index records `sorry` transitively.\n"
                     "Generated by `scripts/import_surface.py`. -/\n")
    inventory = {"default_import": "NLAlib", "complete_import": "NLAlib.Experimental",
                 "experimental_roots": sorted(roots), "default_modules": sorted(safe),
                 "excluded_modules": {m: sorted(c) for m, c in sorted(causes.items()) if c}}
    return {ROOT / "NLAlib.lean": default,
            ROOT / "NLAlib/Experimental.lean": experimental,
            ROOT / "atlas/import_surface.json": json.dumps(inventory, indent=1) + "\n"}


def generate(check=False):
    stale = []
    for path, content in surfaces().items():
        if check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(content)
    if stale:
        raise ValueError("Import surface is stale: " + ", ".join(stale) +
                         "; run python3 scripts/reorg.py --gen-aggregators")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        generate(args.check)
    except ValueError as error:
        parser.exit(1, f"{error}\n")
    print("import surface " + ("OK" if args.check else "generated"))
